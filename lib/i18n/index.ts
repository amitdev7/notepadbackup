export type TranslationKey = keyof (typeof TRANSLATIONS)["en-US"]

/**
 * Translates a key according to the selected language with fallback to en-US.
 * Supports placeholder interpolation, e.g. {key}.
 */
export function t(key: TranslationKey, lang: SupportedLanguage = "en-US", params?: Record<string, string>): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS["en-US"]
  let text: string = (dict as any)[key] || (TRANSLATIONS["en-US"] as any)[key] || String(key)

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), v)
    }
  }

  return text
}
